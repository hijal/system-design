export type Locale = 'bn' | 'en';
export function localizedHref(href: string, locale: Locale): string {
	const [path, hash] = href.split('#');
	return `${path}${path.includes('?') ? '&' : '?'}lang=${locale}${hash ? `#${hash}` : ''}`;
}
